#!/usr/bin/env node

/**
 * Build script for Hexactra Chrome extension
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const distDir = path.join(__dirname, 'dist');
const srcDir = path.join(__dirname, 'src');
const manifestDir = path.join(__dirname, 'manifest');

// Clean dist directory
if (fs.existsSync(distDir)) {
  fs.rmSync(distDir, { recursive: true, force: true });
}
fs.mkdirSync(distDir, { recursive: true });

console.log('Building Hexactra Chrome extension...');

// Copy manifest
const manifestPath = path.join(manifestDir, 'manifest.json');
if (fs.existsSync(manifestPath)) {
  fs.copyFileSync(manifestPath, path.join(distDir, 'manifest.json'));
  console.log('Copied manifest.json');
}

// Copy sidepanel HTML
const sidepanelHtmlPath = path.join(__dirname, 'sidepanel.html');
if (fs.existsSync(sidepanelHtmlPath)) {
  fs.copyFileSync(sidepanelHtmlPath, path.join(distDir, 'sidepanel.html'));
  console.log('Copied sidepanel.html');
}

// Compile TypeScript files
console.log('Compiling TypeScript...');

try {
  execSync('tsc --project tsconfig.json', {
    stdio: 'inherit',
    cwd: __dirname,
  });
  console.log('TypeScript compilation complete');
} catch (error) {
  console.error('TypeScript compilation failed:', error);
  process.exit(1);
}

// Copy compiled files from src to root dist directory
const files = fs.readdirSync(srcDir);
for (const file of files) {
  if (file.endsWith('.js')) {
    fs.copyFileSync(
      path.join(srcDir, file),
      path.join(distDir, file)
    );
    console.log(`Copied ${file}`);
  }
}

// The shared sensitive-text patterns (packages/contracts, generated by
// scripts/gen-sensitive-patterns.mjs): masked screenshots read them (#539).
const patternsPath = path.join(__dirname, '..', '..', 'packages', 'contracts', 'sensitive-patterns.json');
if (!fs.existsSync(patternsPath)) {
  console.error('Missing', patternsPath, '(masked screenshots need it)');
  process.exit(1);
}
fs.copyFileSync(patternsPath, path.join(distDir, 'sensitive-patterns.json'));
console.log('Copied sensitive-patterns.json');

// Copy the brand icons (rendered from docs/brand by scripts/brand/render-icons.mjs)
const iconsSrc = path.join(__dirname, 'icons');
const iconsDir = path.join(distDir, 'icons');
fs.mkdirSync(iconsDir, { recursive: true });
for (const file of fs.readdirSync(iconsSrc)) {
  if (file.endsWith('.png')) {
    fs.copyFileSync(path.join(iconsSrc, file), path.join(iconsDir, file));
    console.log(`Copied icons/${file}`);
  }
}

console.log('Build complete! Output in:', distDir);
console.log('\nTo load the extension in Chrome:');
console.log('1. Open chrome://extensions/');
console.log('2. Enable "Developer mode"');
console.log('3. Click "Load unpacked"');
console.log('4. Select the', distDir, 'directory');
