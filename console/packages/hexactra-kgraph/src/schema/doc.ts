/** The whole of docs/schema.md. Deterministic: the same schemas give the same bytes. */
export function schemaMarkdown(): string {
  const out: string[] = [
    '# Schema',
    '',
    '<!-- Generated by `npm run docs:schema -w @marinoscar/hexactra-kgraph` from src/schema/. Do not edit by hand; test/schema-doc.spec.ts fails when it is stale. -->',
    '',
    'The typed graph of `@marinoscar/hexactra-kgraph`, as JSON Schema generated from the zod schemas in `src/schema/`. Import the schemas from `@marinoscar/hexactra-kgraph/schema`.',
    '',
    '## Version states',
    '',
    '| From | May move to |',
    '|---|---|',
    ...Object.entries(VERSION_TRANSITIONS).map(([from, to]) => `| \`${from}\` | ${to.length ? to.map((t) => `\`${t}\``).join(', ') : '(none: final)'} |`),
    '',
    '## Site fact statuses',
    '',
    '| From | May move to |',
    '|---|---|',
    ...Object.entries(SITE_FACT_TRANSITIONS).map(([from, to]) => `| \`${from}\` | ${to.map((t) => `\`${t}\``).join(', ')} |`),
    '',
  ];
  for (const e of SCHEMA_DOC_ENTRIES) {
    out.push(`## ${e.name}`, '', e.about, '', '```json', JSON.stringify(z.toJSONSchema(e.schema, { io: 'input', unrepresentable: 'any' }), null, 2), '```', '');
  }
  return out.join('\n');
}
