#!/usr/bin/env node
// Draws the Trace mark (docs/brand/hexactra-mark-mono.svg) in Unicode Braille
// for terminals, and writes it to console/apps/cli/src/brand-mark.ts.
//
//   node scripts/brand/render-terminal-mark.mjs [--print]
//
// Each Braille character is a 2x4 dot cell, so a mark of C columns by R rows is
// rendered from a (2C)x(4R) pixel bitmap. Needs Playwright with Chromium.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'console', 'apps', 'cli', 'src', 'brand-mark.ts');
const svg = readFileSync(join(ROOT, 'docs', 'brand', 'hexactra-mark-mono.svg'), 'utf8').replace('<svg ', '<svg style="color:#000" ');

// Sizes in terminal cells (columns x rows). Terminal cells are about twice as
// tall as wide, so a square mark is drawn twice as many columns as rows.
const SIZES = { large: [14, 7], small: [10, 5] };

// Braille dot bits, by [x][y] inside the 2x4 cell.
const BITS = [
  [0x01, 0x02, 0x04, 0x40],
  [0x08, 0x10, 0x20, 0x80],
];

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
// Headful, never headless (AGENTS.md, "Never a headless browser"): without a desktop, run under `xvfb-run -a`.
const browser = await chromium.launch({ headless: false });
const page = await browser.newPage();
await page.setContent('<html><body></body></html>');

const marks = {};
for (const [name, [cols, rows]] of Object.entries(SIZES)) {
  const w = cols * 2;
  const h = rows * 4;
  // Cells are not square, so the bitmap is stretched vertically to keep the
  // hexagon's proportions on screen: draw at w x w, then sample h rows from it.
  const alpha = await page.evaluate(
    async ({ svg, w, h }) => {
      const img = new Image();
      img.src = `data:image/svg+xml;base64,${btoa(svg)}`;
      await img.decode();
      const canvas = document.createElement('canvas');
      canvas.width = w;
      canvas.height = h;
      const ctx = canvas.getContext('2d');
      ctx.drawImage(img, 0, 0, w, h);
      return Array.from(ctx.getImageData(0, 0, w, h).data.filter((_, i) => i % 4 === 3));
    },
    { svg, w, h },
  );
  const lines = [];
  for (let r = 0; r < rows; r++) {
    let line = '';
    for (let c = 0; c < cols; c++) {
      let code = 0;
      for (let x = 0; x < 2; x++) {
        for (let y = 0; y < 4; y++) {
          if (alpha[(r * 4 + y) * w + c * 2 + x] > 96) code |= BITS[x][y];
        }
      }
      line += String.fromCharCode(0x2800 + code);
    }
    lines.push(line.replace(/⠀+$/, ''));
  }
  marks[name] = lines;
}
await browser.close();

if (process.argv.includes('--print')) {
  for (const [name, lines] of Object.entries(marks)) console.log(`${name}:\n${lines.join('\n')}\n`);
}

const body = Object.entries(marks)
  .map(([name, lines]) => `  ${name}: [\n${lines.map((l) => `    ${JSON.stringify(l)},`).join('\n')}\n  ],`)
  .join('\n');
writeFileSync(
  OUT,
  `// GENERATED by scripts/brand/render-terminal-mark.mjs from docs/brand/hexactra-mark-mono.svg.
// Do not edit by hand: change the SVG and re-run the script.

/** The Trace mark in Unicode Braille, for terminal banners. */
export const TRACE_MARK = {
${body}
} as const;
`,
);
console.log(`wrote ${OUT.slice(ROOT.length + 1)}`);
