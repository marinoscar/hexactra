#!/usr/bin/env node
// Writes packages/contracts/sensitive-patterns.json, the extension's copy of
// the console's sensitive-text pattern table (E35.3, #538), from
// console/packages/shared/sensitive-patterns.js. The extension reads the JSON;
// nobody hand-copies the patterns.
//
//   node scripts/gen-sensitive-patterns.mjs           # rewrite the file
//   node scripts/gen-sensitive-patterns.mjs --check   # exit 1 when it is stale (CI)
//
// No dependencies: the pattern module is plain CommonJS.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(root, 'console', 'packages', 'shared', 'sensitive-patterns.js');
const TARGET = join(root, 'packages', 'contracts', 'sensitive-patterns.json');

const require = createRequire(import.meta.url);
const table = require(SOURCE);

const doc = {
  $comment: `Generated by scripts/gen-sensitive-patterns.mjs from ${relative(root, SOURCE)}. Do not edit; rerun the script.`,
  version: table.SENSITIVE_PATTERNS_VERSION,
  maskChar: table.MASK_CHAR,
  checks: Object.keys(table.CHECKS),
  maskKinds: ['last4', 'iban', 'email', 'literal', 'url'],
  patterns: table.SENSITIVE_PATTERNS.map((p) => ({
    id: p.id,
    description: p.description,
    shownAs: p.shownAs,
    source: p.source,
    flags: p.flags,
    check: p.check,
    mask: { ...p.mask },
  })),
};

// Every regex must compile in this engine (V8, as in Chrome).
for (const p of doc.patterns) new RegExp(p.source, p.flags);

const text = `${JSON.stringify(doc, null, 2)}\n`;
const check = process.argv.includes('--check');

if (check) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    // missing: stale
  }
  if (current !== text) {
    console.error(`${relative(root, TARGET)} is stale: run node scripts/gen-sensitive-patterns.mjs and commit the result.`);
    process.exit(1);
  }
  console.log(`${relative(root, TARGET)} OK: version ${doc.version}, ${doc.patterns.length} patterns`);
} else {
  writeFileSync(TARGET, text);
  console.log(`wrote ${relative(root, TARGET)}: version ${doc.version}, ${doc.patterns.length} patterns`);
}
